$save.Add_Click({
    try {
        $g=$groqBox.Text.Trim();$c=$cohereBox.Text.Trim()
        $existing=Read-Presence
        if (-not $g -and -not $c -and -not $existing.extractionProviderConfigured) {
            [Windows.Forms.MessageBox]::Show('Enter a Groq or Cohere API key for memory extraction.','API key required') | Out-Null
            return
        }
        if ($g) { Store-Secret 'groq-api-key' $g }
        if ($c) { Store-Secret 'cohere-api-key' $c }
        Ensure-RouterKey
        $groqBox.Clear();$cohereBox.Clear();Refresh-Status
        [Windows.Forms.MessageBox]::Show('Credentials saved to private user files. Provision or start MemoryCore with the existing Windows lifecycle scripts, then test Tencent login.','Saved') | Out-Null
    } catch {
        [Windows.Forms.MessageBox]::Show('Credential setup failed: '+$_.Exception.Message,'Save failed') | Out-Null
    }
})
$provision.Add_Click({
    try {
        $manager=Join-Path $PSScriptRoot '..\manage_native_windows.ps1'
        if (-not (Test-Path -LiteralPath $manager -PathType Leaf)) {
            # Files installed by the MSI live in source/native/windows, whereas
            # this wizard is installed at the Program Files payload root.
            $manager=Join-Path $PSScriptRoot 'source\native\windows\manage_native_windows.ps1'
        }
        if (-not (Test-Path -LiteralPath $manager -PathType Leaf)) { throw 'WINDOWS_MEMORY_LIFECYCLE_NOT_INSTALLED' }
        # The authoritative lifecycle checks actual MemoryCore health before
        # modifying any metadata; never manufacture an owner key in this GUI.
        & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $manager -Mode Plan -MemoryAction provision -Apply | Out-Null
        if ($LASTEXITCODE -ne 0) { throw 'MEMORY_IDENTITY_PROVISION_FAILED_OR_CORE_NOT_RUNNING' }
        Refresh-Status
        [Windows.Forms.MessageBox]::Show('Local MemoryCore identity provisioned. Test Tencent login next.','Memory ready') | Out-Null
    } catch {
        [Windows.Forms.MessageBox]::Show('MemoryCore provisioning is not ready: '+$_.Exception.Message+'. Check the project installation and MemoryCore status.','Memory pending') | Out-Null
    }
})
$verify.Add_Click({
    $state=Verify-Tencent
    if($state.ready) {
        [Windows.Forms.MessageBox]::Show('Tencent owner identity verified against local MemoryPanel. The dashboard uses the same identity for automatic sign in.','Tencent ready') | Out-Null
        Start-Process $dashboardUrl
    } else {
        [Windows.Forms.MessageBox]::Show('Tencent is not yet ready: '+$state.reason+'. Run native MemoryCore identity provisioning, then retry.','Tencent pending') | Out-Null
    }
    Refresh-Status
})
