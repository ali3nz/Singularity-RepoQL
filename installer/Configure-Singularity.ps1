function Refresh-Status {
    $p=Read-Presence
    $status.Text=('Extraction: '+$(if($p.extractionProviderConfigured){'configured'}else{'key needed'})+'   |   Tencent identity: '+$(if($p.tencentOwnerIdentityProvisioned){'found'}else{'pending memory setup'})+"`r`n"+'The original Tencent dashboard will sign in through the local proxy once MemoryCore is provisioned and running.')
}
Refresh-Status
