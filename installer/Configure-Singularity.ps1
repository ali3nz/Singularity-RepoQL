#Requires -Version 5.1
<#
Per-user first-run credential and Tencent dashboard enrollment for Singularity
RepoQL. Run as the interactive Windows user, never an MSI elevated custom action.

The keys Groq/Cohere are for MemoryCore's extraction failover router, not a
Tencent Cloud API. Tencent's MemoryPanel owner identity is generated by the
existing provision_memory_identity.mjs after the local MemoryCore is running.
The dashboard discovers that very same key file, then issues a short-lived,
HttpOnly, same-origin session. No API key is embedded in an installer, URL,
PowerShell argument, public config, or browser JavaScript.
#>
[CmdletBinding()]
param([ValidateSet('Wizard','Status','VerifyTencent')][string]$Mode='Wizard')
Set-StrictMode -Version Latest
$ErrorActionPreference='Stop'
if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT) { throw 'WINDOWS_ONLY' }
if (-not $env:LOCALAPPDATA) { throw 'LOCALAPPDATA_REQUIRED' }
$memoryRoot=Join-Path $env:LOCALAPPDATA 'Singularity\WindowsNative\memory'
$secretDir=Join-Path $memoryRoot 'state\secrets'
$ownerKey=Join-Path $secretDir 'admin-user-key'
$routerKey=Join-Path $secretDir 'router-access-key'
$dashboardUrl='http://127.0.0.1:18100/#/unified/tencent'
$identity=[Security.Principal.WindowsIdentity]::GetCurrent()
if (-not $identity -or -not $identity.User) { throw 'WINDOWS_IDENTITY_REQUIRED' }
function Assert-LocalOwnedPath([string]$value) {
    if (-not [IO.Path]::IsPathRooted($value) -or $value.StartsWith('\\')) { throw 'UNEXPECTED_REMOTE_PATH' }
    for($cursor=[IO.Path]::GetFullPath($value);$cursor;$cursor=[IO.Path]::GetDirectoryName($cursor)) {
        if(Test-Path -LiteralPath $cursor) {
            $item=Get-Item -LiteralPath $cursor -Force
            if($item.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'REPARSE_PATH_REFUSED' }
        }
        if([IO.Path]::GetDirectoryName($cursor) -eq $cursor) { break }
    }
}
function Restrict-File([string]$path) {
    $acl=[Security.AccessControl.FileSecurity]::new()
    $acl.SetAccessRuleProtection($true,$false)
    foreach ($sid in @($identity.User,[Security.Principal.SecurityIdentifier]::new('S-1-5-18'))) {
        $rule=[Security.AccessControl.FileSystemAccessRule]::new($sid,[Security.AccessControl.FileSystemRights]::FullControl,[Security.AccessControl.AccessControlType]::Allow)
        $acl.AddAccessRule($rule)
    }
    Set-Acl -LiteralPath $path -AclObject $acl
}
function Initialize-SecretDir {
    Assert-LocalOwnedPath $secretDir
    if (-not (Test-Path -LiteralPath $secretDir -PathType Container)) {
        $null=New-Item -Path $secretDir -ItemType Directory -Force
    }
    $acl=[Security.AccessControl.DirectorySecurity]::new()
    $acl.SetAccessRuleProtection($true,$false)
    $inherit=[Security.AccessControl.InheritanceFlags]'ContainerInherit, ObjectInherit'
    foreach ($sid in @($identity.User,[Security.Principal.SecurityIdentifier]::new('S-1-5-18'))) {
        $rule=[Security.AccessControl.FileSystemAccessRule]::new($sid,[Security.AccessControl.FileSystemRights]::FullControl,$inherit,[Security.AccessControl.PropagationFlags]::None,[Security.AccessControl.AccessControlType]::Allow)
        $acl.AddAccessRule($rule)
    }
    Set-Acl -LiteralPath $secretDir -AclObject $acl
}
function Store-Secret([string]$name,[string]$value) {
    if ($name -notin @('groq-api-key','cohere-api-key','router-access-key')) { throw 'UNSUPPORTED_SECRET' }
    if (-not $value -or $value.Length -gt 4096 -or $value.Contains("`n") -or $value.Contains("`r")) { throw 'INVALID_CREDENTIAL' }
    Initialize-SecretDir
    $path=Join-Path $secretDir $name
    Assert-LocalOwnedPath $path
    $temp=Join-Path $secretDir ('.'+[Guid]::NewGuid().ToString('N')+'.new')
    try {
        [IO.File]::WriteAllText($temp,$value,[Text.UTF8Encoding]::new($false))
        Restrict-File $temp
        # The existing source's router reads the key file on startup. Never
        # mutate the running service's environment or print the credential.
        if ([IO.File]::Exists($path)) {
            [IO.File]::Replace($temp,$path,$null,$true)
        } else {
            [IO.File]::Move($temp,$path)
        }
        Restrict-File $path
    } finally {
        if ([IO.File]::Exists($temp)) { [IO.File]::Delete($temp) }
    }
}
function Ensure-RouterKey {
    if (Test-Path -LiteralPath $routerKey -PathType Leaf) { return }
    $bytes=New-Object byte[] 48
    $rng=[Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
    Store-Secret 'router-access-key' ([Convert]::ToBase64String($bytes))
}
function Read-Presence {
    $groq=Test-Path -LiteralPath (Join-Path $secretDir 'groq-api-key') -PathType Leaf
    $cohere=Test-Path -LiteralPath (Join-Path $secretDir 'cohere-api-key') -PathType Leaf
    [ordered]@{
        schema='singularity-first-run-credentials/1'
        extractionProviderConfigured=($groq -or $cohere)
        groqKeyConfigured=$groq
        cohereKeyConfigured=$cohere
        privateRouterKeyConfigured=(Test-Path -LiteralPath $routerKey -PathType Leaf)
        tencentOwnerIdentityProvisioned=(Test-Path -LiteralPath $ownerKey -PathType Leaf)
        # File presence is not proof that Tencent MemoryCore is running.
        tencentDashboardAutoSignIn='REQUIRES_LIVE_SESSION_TEST'
        tencentPanelEndpoint='http://127.0.0.1:18126'
    }
}
function Verify-Tencent {
    if (-not (Test-Path -LiteralPath $ownerKey -PathType Leaf)) {
        return @{ready=$false;reason='MEMORYCORE_OWNER_IDENTITY_NOT_YET_PROVISIONED'}
    }
    # This is the real local MemoryPanel identity; no fallback to a Dockerhost.
    $key=[IO.File]::ReadAllText($ownerKey,[Text.Encoding]::UTF8).Trim()
    if (-not $key -or $key.Length -gt 4096) { return @{ready=$false;reason='LOCAL_OWNER_KEY_INVALID'} }
    try {
        $reply=Invoke-RestMethod -Uri 'http://127.0.0.1:18126/api/v1/meta/auth/verify' -Method Post -ContentType 'application/json' -Body (@{user_key=$key}|ConvertTo-Json -Compress) -Headers @{'X-Tdai-Service-Id'='default'} -TimeoutSec 8
        if ($reply.code -eq 0 -and $reply.data.valid -eq $true -and $null -ne $reply.data.user) {
            return @{ready=$true;reason='LOCAL_OWNER_SESSION_VERIFIED'}
        }
        return @{ready=$false;reason='TENCENT_REJECTED_LOCAL_OWNER_KEY'}
    } catch {
        return @{ready=$false;reason='LOCAL_TENCENT_PANEL_UNAVAILABLE_OR_REJECTED'}
    }
}
if ($Mode -eq 'Status') { Read-Presence | ConvertTo-Json; return }
if ($Mode -eq 'VerifyTencent') { Verify-Tencent | ConvertTo-Json; return }

