// Regression contract for the B4 attach harness (installation options 3/4).
//
// Job-3 findings 6-7: the harness compared AGENTS.md byte-for-byte even though
// the attach's documented behaviour is a managed-block MERGE, and it rolled
// back from "the newest backup dir", which after the idempotence re-attach is
// the credentials-only dir rather than the bundle manifest. Both assertions
// were wrong, so a correct attach was reported as a failure.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const HARNESS = join(ROOT, "tests/acceptance/attach-harness.sh");

test("the attach harness verifies AGENTS.md as a managed-block merge", () => {
  const sh = readFileSync(HARNESS, "utf8");
  assert.match(sh, /managed-block merge/, "the harness names the documented merge semantics");
  assert.match(sh, /singularity:managed:begin v1/);
  assert.match(sh, /singularity:managed:end v1/);
  assert.match(sh, /Unrelated user rules of THIS instance/, "the user's own bytes must survive the merge");
});

test("the attach harness rolls back from the manifest the attach reported", () => {
  const sh = readFileSync(HARNESS, "utf8");
  assert.doesNotMatch(sh, /ls -1dt/, "the newest backup dir is credentials-only after a second attach");
  assert.match(sh, /MANIFEST/, "the rollback input is the manifest the attach reported");
  assert.match(sh, /attach-openchamber\.mjs" rollback --backup-dir/, "the harness uses the supported rollback entrypoint");
  assert.match(sh, /pkg-secrets-before/, "package-level secrets generated by the attach are verified after rollback");
});

test("the attach harness is syntactically valid bash", () => {
  // Feed the script over stdin: this never asks a WSL bash to translate a
  // native Windows path, and still syntax-checks the exact harness bytes.
  const r = spawnSync("bash", ["-n"], { input: readFileSync(HARNESS, "utf8"), encoding: "utf8" });
  assert.equal(r.status, 0, r.stderr);
});
