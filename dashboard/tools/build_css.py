#!/usr/bin/env python3
"""Concatenate the stylesheet <link>s in static/index.html (in cascade order) into static/bundle.css.
Links with a media attribute are wrapped in @media. Source files stay in static/ and remain the
editable originals; re-run after editing any of them:  python3 tools/build_css.py
Then bump the ?v= on the bundle link in index.html."""
import re, pathlib, sys
S = pathlib.Path(__file__).resolve().parent.parent / "static"
html = (S / "index.html").read_text()
SRC = S / "bundle.sources"
names = SRC.read_text().split() if SRC.exists() else None
if names is None:
    sys.exit("static/bundle.sources missing")
out = ["/* GENERATED by tools/build_css.py — edit the source files, not this one. */\n"]
for line in names:
    name, _, media = line.partition("@")
    css = (S / name).read_text()
    out.append(f"\n/* ==== {name} ==== */\n" + (f"@media {media} {{\n{css}\n}}\n" if media else css + "\n"))
(S / "bundle.css").write_text("".join(out))
print("bundle.css", sum(len(x) for x in out), "bytes from", len(names), "files")
